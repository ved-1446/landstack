def test_no_pdf_means_no_issue_row(auth, plots, conn, monkeypatch):
    clean_slate(conn)
    monkeypatch.setattr(pdf, "build_passport_pdf", lambda *a, **k: 1 / 0)
    quiet = TestClient(app, raise_server_exceptions=False)
    r = quiet.get(f"/plots/{plots['clean']}/passport.pdf", headers=auth("officer"))
    assert r.status_code == 500 and r.json() == {"detail": "Internal server error"}
    assert issues(conn, "test_officer") == []                              # rolled back: nothing to verify
    assert [a[1] for a in audit_rows(conn, "test_officer")] == ["download_passport_pdf"]   # the attempt is still logged


