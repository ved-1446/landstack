@pytest.mark.parametrize("change", [
    "UPDATE registrations SET owner_name = 'Someone Else Entirely' WHERE ulpin = %(u)s",
    "UPDATE ror_records SET recorded_area_sqm = recorded_area_sqm + 100 WHERE ulpin = %(u)s",
    "UPDATE tax_records SET paid_until = paid_until - 400 WHERE ulpin = %(u)s",
])
def test_verify_notices_a_changed_record(anon_client, auth, plots, conn, change):
    ulpin = plots["clean"]
    doc_id = doc_id_in(text_of(pdf_of(anon_client, auth, "officer", ulpin)))
    assert anon_client.get(f"/verify/{doc_id}").json()["status"] == "matches"

    tx = appdb.connect()                                    # the change is made here and NEVER committed
    app.dependency_overrides[get_conn] = lambda: tx          # so the API reads this transaction for a moment
    try:
        tx.execute(change, {"u": ulpin})
        r = anon_client.get(f"/verify/{doc_id}")
        assert r.status_code == 200
        assert r.json() == {"valid": False, "ulpin": ulpin, "issued_at": r.json()["issued_at"], "status": CHANGED}
        assert "Someone Else" not in r.text
    finally:
        app.dependency_overrides.pop(get_conn, None)
        tx.rollback()
        tx.close()
    assert anon_client.get(f"/verify/{doc_id}").json()["status"] == "matches"      # the real data never changed


