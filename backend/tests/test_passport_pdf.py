def test_content_hash_is_stable_and_sensitive():
    base = {"ulpin": "MH000100000001", "score": 10, "tax": {"paid_until": date(2026, 1, 6)},
            "ror": {"owner_name": "A B", "recorded_area_sqm": Decimal("1845.65")}, "findings": []}
    shuffled = {"findings": [], "ror": {"recorded_area_sqm": Decimal("1845.65"), "owner_name": "A B"},
                "tax": {"paid_until": date(2026, 1, 6)}, "score": 10, "ulpin": "MH000100000001"}
    assert passport.content_hash(base) == passport.content_hash(shuffled)               # key order does not matter
    assert re.fullmatch(r"[0-9a-f]{64}", passport.content_hash(base))
    assert passport.content_hash({**base, "score": 11}) != passport.content_hash(base)  # any change shows
    assert passport.canonical_json(base) == ('{"findings":[],"ror":{"owner_name":"A B","recorded_area_sqm":"1845.65"},'
                                             '"score":10,"tax":{"paid_until":"2026-01-06"},"ulpin":"MH000100000001"}')


