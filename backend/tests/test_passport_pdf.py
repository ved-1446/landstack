"""Phase 8: the printable passport and /verify.

Runs on the live Docker database (skipped if it is down) with the throw-away users from conftest.py.
Everything it writes (issue rows, audit rows) belongs to those users and is removed at the end.
Record changes are made inside a transaction that is always rolled back.
"""
import io
import re
from pathlib import Path
from datetime import date, datetime, timezone
from decimal import Decimal

import pytest
from fastapi.testclient import TestClient
from pypdf import PdfReader

from backend.app import config, db as appdb, pdf, passport
from backend.app.db import get_conn
from backend.app.main import app

ROOT = Path(__file__).resolve().parents[2]
UNKNOWN = "MH999999999999"
ULPIN_LIKE = re.compile(r"\b(?=[A-Z0-9]*\d)[A-Z0-9]{14}\b")
DOC_ID = re.compile(r"\b[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}\b")
CHANGED = "records have changed since this was issued"
TEST_NAMES = ["test_admin", "test_officer", "test_citizen_a", "test_citizen_b"]


def text_of(content):
    reader = PdfReader(io.BytesIO(content))
    assert len(reader.pages) == 1                                # one A4 page
    return re.sub(r"\s+", " ", " ".join(page.extract_text() for page in reader.pages))


def doc_id_in(text):
    ids = set(DOC_ID.findall(text))
    assert len(ids) == 1, ids
    return ids.pop()


def pdf_of(client, auth, who, ulpin):
    r = client.get(f"/plots/{ulpin}/passport.pdf", headers=auth(who))
    assert r.status_code == 200, r.text
    return r.content


def issues(conn, username):
    return conn.execute("SELECT doc_id, ulpin, issued_to, content_hash FROM passport_issues "
                        "WHERE issued_to = %s ORDER BY issued_at, doc_id", (username,)).fetchall()


def audit_rows(conn, username):
    return conn.execute("SELECT ulpin, action, role FROM audit_log WHERE username = %s ORDER BY id",
                        (username,)).fetchall()


def clean_slate(conn):
    conn.execute("DELETE FROM audit_log WHERE username = ANY(%s::text[])", (TEST_NAMES,))
    conn.execute("DELETE FROM passport_issues WHERE issued_to = ANY(%s::text[])", (TEST_NAMES,))


def only(truth, ctype):
    return sorted(u for u, t in truth["conflicts"].items() if t == [ctype])[0]


@pytest.fixture
def plots(users):
    a = users["citizen_a"]["plots"]            # overlap plot, missing-record plot, clean plot
    return {"overlap": a[0], "missing": a[1], "clean": a[2], "b_own": users["citizen_b"]["plots"][0]}


